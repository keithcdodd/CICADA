function S = cicada_task_glm_group_preflight(cfg)
% CICADA_TASK_GLM_GROUP_PREFLIGHT  Verified unsmoothed Group-mode design.
%
% Experimental source-integrated, READ-ONLY preflight. Only accepts a new
% producer-attested matched_temporal_ica recipe with zero smoothing and
% no voxelwise scaling. It does not run Group processing, ICA or FILM.
% It reuses the existing original design/HRF/contrast preflight, then
% constructs the FSL-centered full-ICA temporal operator, its supported
% time coordinates and an original-time covariance propagation map.
% No p/t/z inference is claimed. Group export is NOT enabled here.

assert(isstruct(cfg) && isscalar(cfg) && ...
    isfield(cfg,'groupRecipe') && isfile(char(cfg.groupRecipe)), ...
    'groupRecipe must name a producer-time Group recipe JSON');
assert(isfield(cfg,'driftModel') && ...
    strcmpi(char(string(cfg.driftModel)),'polynomial'), ...
    'This Group mode requires explicitly configured polynomial drift');
if isfield(cfg,'driftDegree') && ~isempty(cfg.driftDegree)
    assert(isequal(cfg.driftDegree,2), ...
        'Initial Group mode supports degree-2 polynomial detrending only');
end
assert(exist('cicada_group_producer_recipe_v01','file')==2, ...
    'Group recipe verifier is unavailable');
recipeFile=char(cfg.groupRecipe);
Q=cicada_group_producer_recipe_v01('verify',recipeFile);
assert(strcmp(char(Q.RequestedProcessing.EffectiveProcessingPath), ...
    'matched_temporal_ica'), ...
    'Only matched temporal/ICA Group preparation is supported');
assert(isfield(Q,'ActualSpatial') && ...
    isfield(Q.ActualSpatial,'GaussianFWHMmm') && ...
    isfield(Q.ActualSpatial,'VoxelwiseScalingEnabled') && ...
    isequal(double(Q.ActualSpatial.GaussianFWHMmm),0) && ...
    ~logical(Q.ActualSpatial.VoxelwiseScalingEnabled), ...
    'Initial Group mode is restricted to unsmoothed, unscaled outputs');
assert(isfield(Q,'RequestedProcessing') && ...
    isequal(double(Q.RequestedProcessing.DetrendDegree),2), ...
    'Group recipe is not degree-2 detrended');

% This existing validated preflight checks BIDS timing, original CICADA
% ICA selection, complete raw-HRF design, named contrasts and output guards.
baseCfg=cfg;
baseCfg.driftModel='polynomial';
baseCfg.driftDegree=2;
S=cicada_task_glm_preflight(baseCfg);
% Check producer run identity against the selected acquisition directory.
[scanParent,runLabel]=fileparts(S.scanDir);
[scanParent,sesLabel]=fileparts(scanParent);
[~,subLabel]=fileparts(scanParent);
assert(isfield(Q,'Run') && all(isfield(Q.Run, ...
    {'Subject','Session','Task'})), 'Recipe lacks run identity');
recSub=char(string(Q.Run.Subject));
recSes=char(string(Q.Run.Session));
if ~startsWith(recSub,'sub-'), recSub=['sub-' recSub]; end
if ~startsWith(recSes,'ses-'), recSes=['ses-' recSes]; end
assert(strcmp(recSub,subLabel) && strcmp(recSes,sesLabel) && ...
    strcmp(char(string(Q.Run.Task)),runLabel), ...
    'Group recipe identifies a different subject/session/task');
N=S.N;
TR=S.glm.TR;
assert(isfield(Q,'ActualTemporal') && ...
    Q.ActualTemporal.n_timepoints==N && ...
    abs(double(Q.ActualTemporal.tr_sec)-TR)<1e-5 && ...
    Q.ActualTemporal.detrend_degree==2 && ...
    strcmp(char(Q.ActualTemporal.operation_order),'detrend_then_filter'), ...
    'Group temporal recipe disagrees with task acquisition');

% Check association to this exact selected ICA and mask, not just its N/TR.
assoc={'FullMelodicMix','NoiseSelection','FunctionalMask'};
source={'mix','noise','mask'};
for i=1:numel(assoc)
    q=Q.Inputs.(assoc{i});
    assert(strcmpi(char(q.sha256), ...
        cicada_task_glm_sha256(S.files.(source{i}))), ...
        'Group recipe input mismatch: %s',assoc{i});
end
assert(isfield(Q.Inputs,'OriginalCopyBOLD') && ...
    isfile(char(Q.Inputs.OriginalCopyBOLD.path)), ...
    'Missing producer-attested original-copy BOLD');
assert(isfield(Q.PreparedBOLD,'GroupPreparedCleanedBOLD'), ...
    'Missing Group-prepared output entry');
groupBold=char(Q.PreparedBOLD.GroupPreparedCleanedBOLD.path);
sourceCopy=char(Q.Inputs.OriginalCopyBOLD.path);
sourceInfo=niftiinfo(sourceCopy);
groupInfo=niftiinfo(groupBold);
scanInfo=niftiinfo(S.files.original);
assert(isequal(double(sourceInfo.ImageSize),double(groupInfo.ImageSize)) && ...
    isequal(double(sourceInfo.ImageSize),double(scanInfo.ImageSize)) && ...
    numel(groupInfo.ImageSize)>=4 && ...
    double(groupInfo.ImageSize(4))==N && ...
    max(abs(double(sourceInfo.Transform.T(:))- ...
        double(groupInfo.Transform.T(:))))<1e-3 && ...
    max(abs(double(scanInfo.Transform.T(:))- ...
        double(groupInfo.Transform.T(:))))<1e-3 && ...
    abs(double(groupInfo.PixelDimensions(4))-TR)<1e-5, ...
    'Source-copy, scan, and Group output geometry/time disagree');

% Reconstruct the fixed temporal operator with the recorded processing
% settings. Never run ICA again or choose noise ICs using task GLM results.
fpass=double(Q.RequestedProcessing.RequestedFrequencyRangeHz(:)');
assert(isempty(fpass) || numel(fpass)==2, ...
    'Invalid requested temporal frequency range');
[T,~,meta]=cicada_temporal_transform(eye(N),TR,fpass,2);
actual=Q.ActualTemporal;
assert(strcmp(char(meta.filter_mode),char(actual.filter_mode)) && ...
    isequal(double(meta.filtered),double(actual.filtered)), ...
    'Current filter mode differs from the producer-time recipe');
if logical(actual.filtered)
    assert(isfield(actual,'filter_numerator_b') && ...
        isfield(actual,'filter_denominator_a') && ...
        numel(meta.filter_numerator_b)==numel(actual.filter_numerator_b) && ...
        numel(meta.filter_denominator_a)==numel(actual.filter_denominator_a) && ...
        norm(double(meta.filter_numerator_b(:))- ...
             double(actual.filter_numerator_b(:)))<1e-10 && ...
        norm(double(meta.filter_denominator_a(:))- ...
             double(actual.filter_denominator_a(:)))<1e-10, ...
        'Butterworth coefficients disagree with producer-time recipe');
end
M=double(readmatrix(S.files.mix));
noise=double(S.glm.noiseICs(:)');
assert(size(M,1)==N && rank(M)==size(M,2), ...
    'MELODIC mixing matrix dimensions or rank invalid');
Mt=T*M;
Mc=Mt-mean(Mt,1);
% FSL nonaggressive regression must use the FULL mixing-matrix pseudoinverse.
McPinv=pinv(Mc);
Rc=eye(N)-Mc(:,noise)*McPinv(noise,:);
J=ones(N,N)/N;
F=Rc*T+J;
rF=rank(F);
assert(rF>=size(S.taskContrastWeights,2)+1 && rF<N, ...
    'Unexpected Group operator supported-space rank');

% Verify removed nuisance directions MODULO the explicit GLM intercept.
nTask=numel(S.glm.taskNames);
originalNuisance=S.glm.X0(:,nTask+2:end);
Qn=orth([ones(N,1),originalNuisance]);
Z=null((eye(N)-J)*F);
projectorGap=norm(Z*Z'-Qn*Qn','fro');
assert(size(Z,2)==size(Qn,2) && projectorGap<1e-7, ...
    'Group removed temporal span differs from matched original nuisance span');
[U,~,~]=svd(F,'econ');
U=U(:,1:rF);
B=U'*F;
assert(rank(B)==rF, 'Group covariance map is rank deficient');

Htab=readtable(S.files.rawHRF,'VariableNamingRule','preserve');
H=double(Htab{:,:});
assert(size(H,2)==nTask && size(H,1)==N, ...
    'Raw HRFs differ from the preflight task design');
Xtask=[ones(N,1), H-mean(H,1)];
Ctask=[zeros(size(S.taskContrastWeights,1),1),S.taskContrastWeights];
Xred=B*Xtask;
assert(rank(Xred)==size(Xred,2) && ...
    size(Ctask,2)==size(Xred,2) && ...
    rF>size(Xred,2), ...
    'Transformed Group task design is rank deficient');

% Keep physical image N for input/output geometry, and distinguish reduced
% fitted time coordinates in S.glm.X0 and the covariance/observation maps.
S.inputMode='group_matched';
S.files.groupPrepared=groupBold;
S.files.groupRecipe=recipeFile;
S.glm.X0=Xred;
S.glm.C0=Ctask;
S.glm.evNames=[{'intercept'},S.glm.taskNames];
S.glm.observationMap=U';
S.glm.covarianceMap=B;
S.glm.rank=size(Xred,2);
S.glm.residualDimension=rF-size(Xred,2);
S.designRank=size(Xred,2);
S.residualDimension=S.glm.residualDimension;
S.numWaves=size(Xred,2)-1;
S.group=struct('recipePath',recipeFile,'originalCopyBOLD',sourceCopy, ...
    'rankF',rF,'removedDimension',N-rF, ...
    'nuisanceProjectorGap',projectorGap, ...
    'smoothingFWHMmm',0,'voxelwiseScaling',false, ...
    'assurance','PRODUCER_TIME_HASH_LINK_FIXED_OPERATOR_CONDITIONAL');
S.contrastVIF=nan(size(S.taskContrastWeights,1),1);
S.scaledDesignCondition=cond(Xred);
fprintf('GROUP MATCHED PREFLIGHT | N=%d, rank(F)=%d, GLM rank=%d, residual=%d\n', ...
    N,rF,size(Xred,2),S.glm.residualDimension);
fprintf('Provenance verified; nuisance projector gap %.3g. NO WRITES.\n', ...
    projectorGap);
end
